import assert from 'node:assert/strict';
import { newRun, recruit, PLAYABLE, movePiece } from '../src/tft-core.mjs';
import { HUD_COUNT, createHudState, hudOptions, hudWireOptions, actHud } from '../src/tft-hud.mjs';
const run = newRun(17), hud = createHudState();
assert.equal(hudOptions(run, hud).length, HUD_COUNT);
assert.equal(hudOptions(run, hud).slice(2, 7).filter(o => o.enabled).length, 5);
assert.equal(hudOptions(run, hud).slice(10, 18).length, 8);
assert.equal(actHud(run, hud, 9).changed, false, 'Empty team cannot fight');
assert.equal(actHud(run, hud, 2).board, true);
const gold = run.gold;
assert.equal(actHud(run, hud, 2).changed, false, 'Sold offer cannot be bought twice');
assert.equal(run.gold, gold);
actHud(run, hud, 18);
const uid = hud.selected;
actHud(run, hud, 34); actHud(run, hud, 35);
assert.equal(run.team[0].items.length, 2);
assert(hudOptions(run, hud)[30].label.includes('Lâmina · Couraça'), 'Selected equipment must be named');
assert.equal(hudOptions(run, hud)[19].enabled, false, 'Empty field slot cannot move an already deployed piece');
actHud(run, hud, 17);
assert.equal(run.bench[7].uid, uid, 'Click empty reserve places into exact slot');
assert.equal(run.team.length, 0);
assert.equal(actHud(run, hud, 107).changed, false, 'Selection metadata is not a gameplay action');
assert.equal(actHud(run, hud, 16).changed, true);
assert.equal(run.bench[6]?.uid, uid, 'Click empty reserve reorders a selected reserve piece');
assert.equal(run.bench[7], null);
actHud(run, hud, 18);
assert.equal(run.team[0].uid, uid, 'Click empty field deploys selected reserve');
assert.equal(run.team[0].items.length, 2);
run.gold = 100;
while (run.team.length < 6) {
  run.shop = [PLAYABLE.find(kind => !run.team.some(u=>u.kind===kind))]; assert(recruit(run,0));
}
run.shop = ['Tank']; assert(recruit(run,0));
const benchUid = run.bench[0].uid, fieldUid = run.team[2].uid;
assert(movePiece(run,fieldUid,{type:'field',cell:8}));
actHud(run, hud, 10); actHud(run, hud, 20);
assert.equal(run.team[2].uid, benchUid);
assert.equal(run.bench[0].uid, fieldUid);
assert.equal(run.team[2].x, -560); assert.equal(run.team[2].y, -700, 'Swap takes the chosen formation square');
actHud(run, hud, 10);
assert.equal(actHud(run, hud, 31).changed, false, 'Copy progress is informational; no paid upgrade');
run.bag.blade++;
assert.equal(actHud(run, hud, 34).board, false, 'Bench equipment does not rebuild the field');
assert.equal(actHud(run, hud, 37).board, false, 'Bench unequip does not rebuild the field');
assert.equal(actHud(run, hud, 32).board, false, 'Bench sale does not rebuild the field');
run.shop = ['Genie'];
assert.equal(actHud(run, hud, 2).board, false, 'Recruiting into reserve does not rebuild the field');
assert.equal(hud.selected, run.bench.find(u => u?.uid === run.nextId - 1).uid, 'New purchase is selected');
assert.equal(actHud(run, hud, 2.5).changed, false, 'Reject non-integer actions');
hud.phase = 'combat';
const snapshot = JSON.stringify(run);
for (let id = 0; id < 46; id++) assert.equal(actHud(run, hud, id).changed, false);
assert.equal(JSON.stringify(run), snapshot, 'Combat controls cannot mutate economy or pieces');
hud.phase = 'reward'; hud.reward = true;
const prior = run.bag.blade;
actHud(run, hud, 39);
assert.equal(run.bag.blade, prior + 1);
assert.equal(actHud(run, hud, 39).changed, false, 'Reward cannot be collected twice');
assert.equal(hud.phase, 'prepare');
assert(hudWireOptions(run, hud).every(o => /^\d\d\|[01]\|/.test(o.text.val)));
assert(hudWireOptions(run, hud).every(o => o.text.tag === 'RawString'), 'Native UI needs literal text, not localization lookup keys');
hud.phase = 'finished';
assert(actHud(run, hud, 9).exit);
for (const phase of ['prepare','combat','reward','finished']) {
  const menuHud = createHudState(); menuHud.phase = phase;
  const economy = JSON.stringify(run);
  assert(actHud(run, menuHud, 46).navigation);
  assert.equal(menuHud.menu, 'open');
  actHud(run,menuHud,133);actHud(run,menuHud,134);assert.equal(menuHud.quality,1);assert.equal(menuHud.font,1);
  actHud(run,menuHud,132);assert.equal(menuHud.menu,'new-confirm');actHud(run,menuHud,47);assert.equal(menuHud.menu,'open');
  assert(hudOptions(run,menuHud).slice(0,46).every(o=>!o.enabled), 'Menu disables all gameplay actions');
  assert.equal(actHud(run,menuHud,2).changed,false);
  assert.equal(actHud(run,menuHud,39).changed,false);
  assert.equal(actHud(run,menuHud,49).changed,false, 'Exit requires the visible confirmation');
  actHud(run,menuHud,48); assert.equal(menuHud.menu,'confirm');
  actHud(run,menuHud,47); assert.equal(menuHud.menu,'open');
  actHud(run,menuHud,47); assert.equal(menuHud.menu,null);
  assert.equal(menuHud.phase,phase,'Continue preserves phase');
  actHud(run,menuHud,46); actHud(run,menuHud,48);
  assert(actHud(run,menuHud,49).exit); assert(menuHud.exiting);
  assert.equal(JSON.stringify(run),economy,'Navigation never changes pieces, gold or prizes');
}
console.log('PASS: permanent HUD, purchases/select, formation-preserving swaps, reserve actions avoid field rebuilds, equipment labels/conservation, invalid and combat actions, single reward collection.');
